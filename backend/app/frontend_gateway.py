"""Render a project-local, rootless Nginx config; never starts or stops a service."""
import os
from pathlib import Path
from urllib.parse import urlsplit

from .config import ROOT, Settings


def quoted(path: Path) -> str:
    value = str(path.resolve())
    if any(c in value for c in ('\n','\r','\x00','$')):
        raise ValueError('Unsupported path in Nginx configuration')
    return '"' + value.replace('\\','\\\\').replace('"','\\"') + '"'


def render(settings: Settings, root: Path = ROOT) -> Path:
    origin = urlsplit(settings.public_origin)
    port = origin.port or (443 if origin.scheme=='https' else 80)
    if port != 8025:
        raise ValueError('This gateway listens on 8025; PUBLIC_ORIGIN must explicitly use :8025.')
    if not (root/'frontend/dist/index.html').is_file():
        raise ValueError('Build frontend first: cd frontend && npm run build')
    runtime = root/'.runtime/nginx'
    runtime.mkdir(parents=True,exist_ok=True,mode=0o700)
    os.chmod(root/'.runtime',0o700)
    for name in ('client_temp','proxy_temp','fastcgi_temp','uwsgi_temp','scgi_temp'):
        (runtime/name).mkdir(exist_ok=True,mode=0o700)
    ssl = ''
    listen_suffix = ''
    if settings.secure_cookie:
        cert,key = Path(settings.tls_cert_file),Path(settings.tls_key_file)
        if not settings.tls_cert_file or not settings.tls_key_file or not cert.is_file() or not key.is_file():
            raise ValueError('HTTPS requires TLS_CERT_FILE and TLS_KEY_FILE; refusing to fall back to HTTP.')
        listen_suffix = ' ssl'
        ssl = f'ssl_certificate {quoted(cert)};\nssl_certificate_key {quoted(key)};\nssl_protocols TLSv1.2 TLSv1.3;'
    hosts = ' '.join(sorted({origin.hostname,'127.0.0.1','localhost'}))
    proxy = '''
        proxy_pass http://127.0.0.1:8026;
        proxy_set_header Host 127.0.0.1:8026;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-Host $host;
        proxy_connect_timeout 5s;
        proxy_read_timeout 30s;
        proxy_send_timeout 15s;
    '''
    config = f'''# Generated by app.frontend_gateway; contains no DB credentials.
worker_processes 1;
pid {quoted(runtime/'nginx.pid')};
error_log stderr warn;
events {{ worker_connections 256; }}
http {{
    server_tokens off;
    access_log off;
    default_type application/octet-stream;
    types {{ text/html html; text/css css; application/javascript js; application/json json;
            image/svg+xml svg; image/png png; image/x-icon ico; font/woff2 woff2; }}
    client_body_temp_path {quoted(runtime/'client_temp')};
    proxy_temp_path {quoted(runtime/'proxy_temp')};
    fastcgi_temp_path {quoted(runtime/'fastcgi_temp')};
    uwsgi_temp_path {quoted(runtime/'uwsgi_temp')};
    scgi_temp_path {quoted(runtime/'scgi_temp')};
    client_max_body_size 128k;
    client_body_timeout 10s;
    client_header_timeout 10s;
    keepalive_timeout 30s;
    send_timeout 15s;
    limit_req_status 429;
    limit_req_zone $binary_remote_addr zone=login:1m rate=10r/m;
    limit_req_zone $binary_remote_addr zone=api:2m rate=120r/m;
    server {{
        listen 0.0.0.0:8025{listen_suffix} default_server;
        server_name _;
        {ssl}
        return 421;
    }}
    server {{
        listen 0.0.0.0:8025{listen_suffix};
        server_name {hosts};
        {ssl}
        root {quoted(root/'frontend/dist')};
        index index.html;
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options "nosniff" always;
        add_header X-Frame-Options "DENY" always;
        add_header Referrer-Policy "no-referrer" always;
        add_header Content-Security-Policy "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; font-src 'self'; connect-src 'self'; object-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'" always;
        location ~ (^|/)\\. {{ return 404; }}
        location ^~ /api/auth/ {{
            client_max_body_size 8k;
            limit_req zone=login burst=10 nodelay;
            {proxy}
        }}
        location /api/ {{
            limit_req zone=api burst=30 nodelay;
            {proxy}
        }}
        location / {{
            limit_except GET {{ deny all; }}
            try_files $uri $uri/ /index.html;
        }}
    }}
}}
'''
    target=runtime/'nginx.conf'
    target.write_text(config,encoding='utf-8')
    target.chmod(0o600)
    return target


def main():
    try:
        target=render(Settings())
    except Exception as exc:
        # Validation errors are generic; don't dump Settings or its source input.
        print('Frontend gateway configuration failed. Check PUBLIC_ORIGIN, build output, and TLS file paths.')
        raise SystemExit(1) from None
    print(f'Gateway configuration written to {target}; no service started.')


if __name__=='__main__':
    main()
